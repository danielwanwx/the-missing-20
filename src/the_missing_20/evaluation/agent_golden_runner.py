    def run_scripted(self) -> dict[str, Any]:
        require_strands()
        reports = [
            self.run_profile(_agent_profile_manifest(self.repository_root, key))
            for key in PROFILE_KEYS
        ]
        return {
            "schema_version": "scripted-strands-proof/v3",
            "status": "PASS" if all(item["status"] == "PASS" for item in reports) else "FAIL",
            "evidence_class": EvidenceClass.SCRIPTED_PROOF.value,
            "provider": "scripted",
            "model": "scripted-strands-v1",
            "strands_required": True,
            "profile_count": len(reports),
            "profiles": reports,
            "runs_per_profile": 2,
            "byte_identical": all(item["scripted_runs"]["byte_identical"] for item in reports),
        }

