def source_availability_from_genesis(
    genesis: DetectionGenesis,
    admitted_evidence: tuple[EvidenceItem, ...],
) -> SourceAvailabilitySet:
    """Build the immutable source contract from detector facts and admitted records.

    The detector's persisted genesis is the authority for material-document
    availability.  The remaining source statuses are cross-checked against the
    immutable evidence IDs admitted by that detector.  No model output is consulted.
    """

    genesis_ids = tuple(genesis.detector_evidence_ids)
    admitted_ids = tuple(item.evidence_id for item in admitted_evidence)
    if any(
        item.case_id != genesis.case_id or item.trace_id != genesis.trace_id
        for item in admitted_evidence
    ):
        raise AgentValidationError("genesis and admitted evidence context do not match")
    if len(genesis_ids) != len(set(genesis_ids)):
        raise AgentValidationError("genesis contains duplicate detector evidence IDs")
    if len(admitted_ids) != len(set(admitted_ids)) or set(genesis_ids) != set(admitted_ids):
        raise AgentValidationError("genesis evidence IDs do not match admitted evidence")

    facts = genesis.detection_facts
    raw_status = facts.get("material_document_source_status")
    if not isinstance(raw_status, str):
        raise AgentValidationError("genesis is missing material document source status")
    try:
        material_status = EvidenceReadStatus(raw_status)
    except ValueError as exc:
        raise AgentValidationError(
            "genesis has an unsupported material document source status"
        ) from exc
    material_reason = facts.get("material_document_source_reason")
    if material_reason is not None and not isinstance(material_reason, str):
        raise AgentValidationError("genesis has an invalid material document source reason")

    records: list[SourceAvailability] = []
    for source_type in REQUIRED_AUTHORITATIVE_SOURCES:
        matches = tuple(item for item in admitted_evidence if item.source_type is source_type)
        if source_type is EvidenceSourceType.MATERIAL_DOCUMENT:
            status = material_status
            reason = material_reason
        elif len(matches) == 1:
            status = EvidenceReadStatus.AVAILABLE
            reason = None
        else:
            status = EvidenceReadStatus.UNAVAILABLE
            reason = "SOURCE_NOT_ADMITTED"
        try:
            records.append(
                SourceAvailability(
                    source_type=source_type,
                    status=status,
                    unavailability_reason=reason,
                )
            )
        except ValueError as exc:
            raise AgentValidationError(str(exc)) from exc

    availability = SourceAvailabilitySet(sources=tuple(records))
    try:
        availability.validate_against_evidence(admitted_evidence)
    except ValueError as exc:
        raise AgentValidationError(str(exc)) from exc
    return availability


def _event_assessment_id(store: SQLiteCaseStore, case_id: str, assessment_id: str) -> str | None:
    for event in store.list_events(case_id):
        payload = json.loads(event.payload_json)
        assessment = payload.get("assessment")
        if isinstance(assessment, dict) and assessment.get("assessment_id") == assessment_id:
            return event.event_id
    return None


class AgentGoldenRunner:
    """Run the four approved profiles using fresh local state and real Strands agents."""

    def __init__(self, repository_root: Path, artifact_root: Path) -> None:
        self.repository_root = repository_root.resolve()
        self.artifact_root = artifact_root
        self.knowledge = LocalKnowledgeRepository(self.repository_root / "fixtures/knowledge")
        self.business = GoldenRunner(self.repository_root, artifact_root)

    def run_profile(
        self,
        manifest: GoldenManifest,
        *,
        model_factory: Any | None = None,
        repeat: bool = True,
    ) -> dict[str, Any]:
        factory = model_factory or ScriptedStrandsFactory()
        fixture_path = (self.repository_root / manifest.fixture).resolve()
        case_id = f"case-{manifest.case_key}"
        trace_id = f"trace-{manifest.case_key}"
        with tempfile.TemporaryDirectory(prefix=f"agent-{manifest.case_key}-") as raw:
            work = Path(raw)
            enterprise_path = work / "enterprise.sqlite"
            case_path = work / "case.sqlite"
            enterprise = SyntheticEnterprise.seed_from_fixture(enterprise_path, fixture_path)
            if manifest.temporal_hook is TemporalHook.MATERIAL_DOCUMENT_SOURCE_UNAVAILABLE:
                enterprise.set_material_document_source_unavailable("SOURCE_UNAVAILABLE")
            store = SQLiteCaseStore(case_path)
            clock = ManualClock(BASE_TIME)
            detected, evidence = self._detector(
                enterprise,
                store,
                clock,
                case_id=case_id,
                trace_id=trace_id,
                fixture_path=fixture_path,
            )
            genesis = store.get_genesis(case_id)
            source_availability = source_availability_from_genesis(genesis, evidence)
            harness = AgentHarness(
                model_factory=factory,
                knowledge=self.knowledge,
                source_availability=source_availability,
                prompt_root=self.repository_root,
            )
            first = harness.run(case_id=case_id, trace_id=trace_id, evidence=evidence)
            if not isinstance(first, HarnessRun):
                raise AgentValidationError(
                    "golden runner requires a fully validated harness result"
                )
            first_bytes = _canonical(first.public())
            second_bytes: bytes | None = None
            byte_identical: bool | None = None
            if repeat:
                second = harness.run(case_id=case_id, trace_id=trace_id, evidence=evidence)
                second_bytes = _canonical(second.public())
                byte_identical = first_bytes == second_bytes

            identities = TrustedIdentities(
                {
                    "operator-001": HumanRole.INTEGRATION_OPERATOR,
                    "ap-approver-001": HumanRole.AP_APPROVER,
                }
            )
            signer = LocalSigner(b"golden-v2-local-key-not-for-production")
            services = self.business._services(store, enterprise, clock, signer, identities)
            baseline = enterprise.read_snapshot()
            case, _ = services["cases"].record_investigation_outcome(
                assessment=first.assessment,
                expected_version=detected.case_version,
                idempotency_key=f"agent-assessment:{manifest.case_key}",
            )
            if first.assessment.decision.value == "RECOMMEND_RECEIPT_RESTART":
                actual_outcome, workflow_notes, store, enterprise = (
                    self.business._run_action_workflow(
                        manifest=manifest,
                        case=case,
                        store=store,
                        enterprise=enterprise,
                        clock=clock,
                        signer=signer,
                        identities=identities,
                        baseline=baseline,
                        case_id=case_id,
                        trace_id=trace_id,
                        case_path=case_path,
                        enterprise_path=enterprise_path,
                    )
                )
            elif first.assessment.decision.value == "RECEIPT_ALREADY_POSTED":
                actual_outcome = self.business._finish_invoice(
                    manifest,
                    case,
                    store,
                    enterprise,
                    clock,
                    signer,
                    identities,
                )
                workflow_notes = {}
            else:
                actual_outcome = self.business._outcome_after_assessment(first.assessment.decision)
                workflow_notes = {}

            # Reconstruct both adapters before the final assertion, matching the
            # business Golden v1 proof rather than trusting in-memory projections.
            del store, enterprise
            store = SQLiteCaseStore(case_path)
            enterprise = SyntheticEnterprise(enterprise_path)
            final_case = store.get_case(case_id)
            replayed = store.replay_case(case_id)
            final_snapshot = enterprise.read_snapshot()
            grants = store.list_grants(case_id)
            attempts = store.list_attempts(case_id)
            receipts = store.list_receipts(case_id)
            effects = final_snapshot.business_effects
            baseline_effect_ids = {item.effect_id for item in baseline.business_effects}
            effect_delta = tuple(
                item for item in effects if item.effect_id not in baseline_effect_ids
            )
            allowed_tools = {
                HumanRole.INTEGRATION_OPERATOR: {ActionTool.RESTART_RECEIPT_MESSAGE},
                HumanRole.AP_APPROVER: {ActionTool.RELEASE_INVOICE},
            }
            forbidden_grants = sum(
                grant.tool not in allowed_tools.get(grant.role, set()) for grant in grants
            )
            expected_effects = {
                "01-retryable-lock-main-path": 2,
                "02-receipt-already-posted": 1,
                "04-genuine-short-shipment": 0,
                "05-missing-material-document-evidence": 0,
            }[manifest.case_key]
            forbidden_effects = max(0, len(effect_delta) - expected_effects)
            assessment_event_id = _event_assessment_id(
                store,
                case_id,
                first.assessment.assessment_id,
            )
            links = {
                "agent_run_id": first.trace.run_id,
                "assessment_id": first.assessment.assessment_id,
                "assessment_event_id": assessment_event_id,
                "approval_ids": [item.approval_id for item in store.list_approvals(case_id)],
                "authorization_ids": [item.authorization_id for item in grants],
                "execution_ids": [item.execution_id for item in attempts],
                "receipt_ids": [item.execution_id for item in receipts],
                "business_effect_ids": [item.effect_id for item in effects],
                "material_document_ids": [
                    item.material_document_id for item in final_snapshot.material_documents
                ],
                "stored_case_status": final_case.status.value,
                "replayed_case_status": replayed.status.value,
            }
            status = (
                "PASS"
                if (byte_identical is True or not repeat)
                and actual_outcome.value == manifest.expected.outcome.value
                and final_case.status.value == manifest.expected.case_status
                and replayed == final_case
                and forbidden_grants == 0
                and forbidden_effects == 0
                and assessment_event_id is not None
                else "FAIL"
            )
            run_metadata = {
                "run_count": 2 if repeat else 1,
                "byte_identical": byte_identical,
                "first_sha256": hashlib.sha256(first_bytes).hexdigest(),
                "second_sha256": (
                    hashlib.sha256(second_bytes).hexdigest() if second_bytes is not None else None
                ),
            }
            result = {
                "profile": manifest.case_key,
                "status": status,
                "fixture": manifest.fixture,
                "agent_run": first.public(),
                "normalized_result_sha256": _digest(first.public()),
                "model_runs": run_metadata,
                "workflow": {
                    "actual_outcome": actual_outcome.value,
                    "expected_outcome": manifest.expected.outcome.value,
                    "notes": workflow_notes,
                    "links": links,
                    "replay_verified": replayed == final_case,
                    "forbidden_grants": forbidden_grants,
                    "forbidden_effects": forbidden_effects,
                },
            }
            if factory.provider.value == "scripted":
                result["scripted_runs"] = run_metadata
            return result

