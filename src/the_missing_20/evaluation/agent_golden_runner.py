    def run_authority_b_advisory(self, model_factory: Any) -> dict[str, Any]:
        """Run exactly one main-case advisory proof and persist redacted evidence.

        This is intentionally separate from the historical four-profile v9 smoke.
        The claim is acquired before any model call, only the main synthetic profile
        is executed, and every provider/validator failure is projected into an
        advisory ``DEGRADED`` outcome without a corrective call.  No operational
        action is read from or authorized by this path.
        """

        require_strands()
        ledger = getattr(model_factory, "ledger", None)
        if ledger is None:
            raise ValueError("Authority-B model factory must expose its shared budget ledger")
        claim = claim_authority_b_attempt(self.repository_root / AUTHORITY_B_CLAIM_PATH)
        manifest = _agent_profile_manifest(self.repository_root, AUTHORITY_B_MAIN_PROFILE)
        fixture_path = (self.repository_root / manifest.fixture).resolve()
        advisory: AdvisoryInvestigation
        try:
            with tempfile.TemporaryDirectory(prefix="authority-b-advisory-") as raw:
                work = Path(raw)
                enterprise_path = work / "enterprise.sqlite"
                case_path = work / "case.sqlite"
                enterprise = SyntheticEnterprise.seed_from_fixture(enterprise_path, fixture_path)
                if manifest.temporal_hook is TemporalHook.MATERIAL_DOCUMENT_SOURCE_UNAVAILABLE:
                    enterprise.set_material_document_source_unavailable("SOURCE_UNAVAILABLE")
                store = SQLiteCaseStore(case_path)
                clock = ManualClock(BASE_TIME)
                detected, evidence = self._detector(
                    enterprise,
                    store,
                    clock,
                    case_id=f"case-{manifest.case_key}",
                    trace_id=f"trace-{manifest.case_key}",
                    fixture_path=fixture_path,
                )
                availability = source_availability_from_genesis(
                    store.get_genesis(detected.case_id), evidence
                )
                harness = AgentHarness(
                    model_factory=model_factory,
                    knowledge=self.knowledge,
                    source_availability=availability,
                    prompt_root=self.repository_root,
                    allow_stage_retries=False,
                )
                run = harness.run(
                    case_id=detected.case_id,
                    trace_id=evidence[0].trace_id,
                    evidence=evidence,
                )
                advisory = advisory_from_harness_run(
                    run,
                    case_version=detected.case_version,
                    now=BASE_TIME,
                    admitted_evidence_ids=(item.evidence_id for item in evidence),
                )
                budget = ledger.snapshot()
                advisory = advisory.model_copy(
                    update={
                        "provider": str(getattr(run.trace, "provider", "bedrock")),
                        "model": str(getattr(run.trace, "model", "unknown")),
                        "usage": AdvisoryUsage(
                            request_count=int(budget.get("request_count", 0)),
                            input_tokens=int(budget.get("input_tokens", 0)),
                            output_tokens=int(budget.get("output_tokens", 0)),
                            latency_ms=sum(
                                int(getattr(stage, "latency_ms", 0))
                                for stage in getattr(run.trace, "stages", ())
                            ),
                            estimated_cost_usd=float(budget.get("incremental_cost_usd", 0.0)),
                        ),
                    }
                )
        except BaseException as error:
            budget = ledger.snapshot()
            advisory = normalize_advisory_failure(
                case_id=f"case-{manifest.case_key}",
                trace_id=f"trace-{manifest.case_key}",
                case_version=1,
                error=error,
                started=True,
                now=BASE_TIME,
                usage=AdvisoryUsage(
                    request_count=int(budget.get("request_count", 0)),
                    input_tokens=int(budget.get("input_tokens", 0)),
                    output_tokens=int(budget.get("output_tokens", 0)),
                    estimated_cost_usd=float(budget.get("incremental_cost_usd", 0.0)),
                ),
            ).model_copy(
                update={
                    "provider": "bedrock",
                    "model": str(
                        getattr(getattr(model_factory, "config", None), "model_id", "unknown")
                    ),
                }
            )
            _atomic_json(
                self.repository_root / AUTHORITY_B_ADVISORY_ARTIFACT,
                advisory.model_dump(mode="json"),
            )
            outcome = AuthorityBOutcome(
                claim_id=claim.claim_id,
                status="DEGRADED",
                provider="bedrock",
                model=advisory.model or "unknown",
                request_count=int(budget.get("request_count", 0)),
                input_tokens=int(budget.get("input_tokens", 0)),
                output_tokens=int(budget.get("output_tokens", 0)),
                estimated_cost_usd=Decimal(str(budget.get("incremental_cost_usd", 0.0))),
                usefulness_status=ProofStatus.FAIL,
                evidence_class=EvidenceClass.NOT_PROVEN,
                error_code=advisory.error_code,
            )
            save_authority_b_outcome(self.repository_root / AUTHORITY_B_FAILURE_PATH, outcome)
            usefulness = build_ai_usefulness_proof(
                proof_id=f"authority-b-usefulness:{AUTHORITY_B_MAIN_PROFILE}",
                advisory=advisory,
                require_real_provider=True,
                evidence_class=EvidenceClass.NOT_PROVEN,
            )
            _atomic_json(
                self.repository_root / AUTHORITY_B_USEFULNESS_ARTIFACT,
                usefulness.model_dump(mode="json"),
            )
            return {
                "schema_version": "authority-b-proof/v1",
                "status": "DEGRADED",
                "claim": claim.model_dump(mode="json"),
                "claim_digest": authority_b_claim_digest(claim),
                "outcome": outcome.model_dump(mode="json"),
                "advisory": advisory.model_dump(mode="json"),
                "usefulness_proof": usefulness.model_dump(mode="json"),
            }

        budget = ledger.snapshot()
        usefulness = build_ai_usefulness_proof(
            proof_id=f"authority-b-usefulness:{AUTHORITY_B_MAIN_PROFILE}",
            advisory=advisory,
            require_real_provider=True,
            evidence_class=EvidenceClass.NOT_PROVEN,
        )
        _atomic_json(
            self.repository_root / AUTHORITY_B_ADVISORY_ARTIFACT,
            advisory.model_dump(mode="json"),
        )
        _atomic_json(
            self.repository_root / AUTHORITY_B_USEFULNESS_ARTIFACT,
            usefulness.model_dump(mode="json"),
        )
        passed = usefulness.status.value == "PASS"
        outcome = AuthorityBOutcome(
            claim_id=claim.claim_id,
            status="PASS" if passed else "DEGRADED",
            provider=advisory.provider or "bedrock",
            model=advisory.model or "unknown",
            request_count=int(budget.get("request_count", 0)),
            input_tokens=int(budget.get("input_tokens", 0)),
            output_tokens=int(budget.get("output_tokens", 0)),
            estimated_cost_usd=Decimal(str(budget.get("incremental_cost_usd", 0.0))),
            usefulness_status=usefulness.status,
            error_code=None if passed else "AUTHORITY_B_USEFULNESS_INCOMPLETE",
        )
        save_authority_b_outcome(
            self.repository_root
            / (AUTHORITY_B_SUCCESS_PATH if passed else AUTHORITY_B_FAILURE_PATH),
            outcome,
        )
        return {
            "schema_version": "authority-b-proof/v1",
            "status": outcome.status,
            "claim": claim.model_dump(mode="json"),
            "claim_digest": authority_b_claim_digest(claim),
            "outcome": outcome.model_dump(mode="json"),
            "advisory": advisory.model_dump(mode="json"),
            "usefulness_proof": usefulness.model_dump(mode="json"),
        }

    def _authority_b_proof(self) -> dict[str, Any]:
        """Read, never rerun, the consumed real Authority-B advisory attempt.

        The acceptance rebaseline promotes a valid *degraded* provider record as
        integration evidence while keeping stable real-model usefulness explicitly
        ``NOT_PROVEN``.  A missing, malformed, mismatched, or successful outcome is
        not silently treated as degradation: it fails closed and cannot promote the
        Golden suite.
        """

        claim_path = self.repository_root / AUTHORITY_B_CLAIM_PATH
        success_path = self.repository_root / AUTHORITY_B_SUCCESS_PATH
        failure_path = self.repository_root / AUTHORITY_B_FAILURE_PATH
        advisory_path = self.repository_root / AUTHORITY_B_ADVISORY_ARTIFACT
        usefulness_path = self.repository_root / AUTHORITY_B_USEFULNESS_ARTIFACT
        base: dict[str, Any] = {
            "schema_version": "authority-b-ai-usefulness-proof/v1",
            "claim": str(AUTHORITY_B_CLAIM_PATH),
            "frozen_evidence_version": AUTHORITY_B_FROZEN_EVIDENCE_VERSION,
            "frozen_evidence_digests": dict(AUTHORITY_B_FROZEN_EVIDENCE_DIGESTS),
            "stable_real_usefulness_status": EvidenceClass.NOT_PROVEN.value,
            "evidence_class": EvidenceClass.NOT_PROVEN.value,
        }

        if not frozen_evidence_matches(self.repository_root):
            return {
                **base,
                "status": "NOT_RUN",
                "evidence_valid": False,
                "reason": "Authority-B evidence bundle failed its frozen source anchor",
                "outcome": str(AUTHORITY_B_FAILURE_PATH),
            }

        if success_path.is_file() or (success_path.exists() and not failure_path.is_file()):
            # A successful outcome is deliberately not accepted by this rebaseline:
            # no artifact may turn stable real Nova usefulness into an unreviewed
            # plain PASS.  Coexisting success/failure files are also tampering.
            return {
                **base,
                "status": EvidenceClass.NOT_PROVEN.value,
                "evidence_valid": False,
                "reason": (
                    "successful or ambiguous real Authority-B outcome is not accepted "
                    "under disclosed-degradation rebaseline"
                ),
                "outcome": str(AUTHORITY_B_SUCCESS_PATH),
            }
        if not failure_path.is_file():
            return {
                **base,
                "status": "NOT_RUN",
                "evidence_valid": False,
                "reason": "real Authority-B advisory proof is not run",
                "outcome": "absent",
            }

        try:
            claim = load_authority_b_attempt_claim(claim_path)
            outcome = AuthorityBOutcome.model_validate_json(failure_path.read_bytes())
            advisory = AdvisoryInvestigation.model_validate_json(advisory_path.read_bytes())
            if not usefulness_path.is_file():
                raise ValueError("real Authority-B usefulness proof artifact is missing")
            usefulness = AIUsefulnessProof.model_validate_json(usefulness_path.read_bytes())
        except (OSError, RuntimeError, ValueError, TypeError, KeyError):
            return {
                **base,
                "status": "NOT_RUN",
                "evidence_valid": False,
                "reason": "real Authority-B degradation artifacts are unreadable",
                "outcome": str(AUTHORITY_B_FAILURE_PATH),
            }

        expected_claim_digest = authority_b_claim_digest(claim)
        usage_matches = (
            outcome.request_count == advisory.usage.request_count
            and outcome.input_tokens == advisory.usage.input_tokens
            and outcome.output_tokens == advisory.usage.output_tokens
            and Decimal(str(advisory.usage.estimated_cost_usd)) == outcome.estimated_cost_usd
        )
        bounded_usage = (
            outcome.request_count <= claim.request_cap
            and outcome.input_tokens <= claim.input_token_cap
            and outcome.output_tokens <= claim.output_token_cap
            and outcome.estimated_cost_usd <= claim.incremental_cost_cap_usd
            and claim.prior_cost_usd + outcome.estimated_cost_usd <= claim.cumulative_cost_cap_usd
        )
        outcome_matches_advisory = (
            outcome.claim_id == claim.claim_id
            and outcome.status == "DEGRADED"
            and outcome.usefulness_status is ProofStatus.FAIL
            and outcome.evidence_class is EvidenceClass.NOT_PROVEN
            and outcome.stable_real_usefulness == EvidenceClass.NOT_PROVEN.value
            and advisory.status.value == "DEGRADED"
            and advisory.authority_label == "ADVISORY — NOT AN OPERATIONAL DECISION"
            and advisory.case_id == f"case-{AUTHORITY_B_MAIN_PROFILE}"
            and advisory.trace_id == f"trace-{AUTHORITY_B_MAIN_PROFILE}"
            and advisory.provider == outcome.provider
            and advisory.model == outcome.model
            and advisory.error_code == outcome.error_code
            and usage_matches
            and bounded_usage
        )
        try:
            usefulness_model = usefulness
            stability_check = next(
                (
                    item
                    for item in usefulness_model.checks
                    if item.check_id == "stable_real_nova_usefulness"
                ),
                None,
            )
            usefulness_matches = (
                usefulness_model.status is ProofStatus.FAIL
                and usefulness_model.evidence_class is EvidenceClass.NOT_PROVEN
                and usefulness_model.advisory_status.value == "DEGRADED"
                and usefulness_model.provider == advisory.provider
                and usefulness_model.requests == outcome.request_count
                and usefulness_model.input_tokens == outcome.input_tokens
                and usefulness_model.output_tokens == outcome.output_tokens
                and Decimal(str(usefulness_model.estimated_cost_usd)) == outcome.estimated_cost_usd
                and usefulness_model.operational_authority is False
                and stability_check is not None
                and stability_check.status is ProofStatus.FAIL
            )
        except (AttributeError, TypeError, ValueError):
            usefulness_matches = False
        valid = (
            claim.claim_digest == expected_claim_digest
            and outcome_matches_advisory
            and usefulness_matches
        )
        if not valid:
            return {
                **base,
                "status": "NOT_RUN",
                "evidence_valid": False,
                "reason": "real Authority-B degradation evidence failed closed validation",
                "outcome": outcome.model_dump(mode="json"),
            }

        return {
            **base,
            "status": EvidenceClass.NOT_PROVEN.value,
            "evidence_valid": True,
            "integration_evidence_class": EvidenceClass.PROVEN.value,
            "outcome_status": outcome.status,
            "usefulness_status": outcome.usefulness_status.value,
            "claim_digest": expected_claim_digest,
            "outcome": outcome.model_dump(mode="json"),
            "advisory": advisory.model_dump(mode="json"),
            "usefulness_proof": usefulness.model_dump(mode="json"),
        }

    def _bedrock_proof(self) -> dict[str, Any]:
        path = self.repository_root / BEDROCK_ARTIFACT
        if not path.is_file():
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "immutable Bedrock smoke artifact is absent",
                "artifact": BEDROCK_ARTIFACT,
            }
        try:
            proof = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "Bedrock smoke artifact is unreadable",
                "artifact": BEDROCK_ARTIFACT,
            }
        if not isinstance(proof, dict) or proof.get("schema_version") != "bedrock-smoke/v5":
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "v8 Bedrock smoke artifact schema is stale or unsupported",
                "artifact": BEDROCK_ARTIFACT,
            }
        if proof.get("status") != "PASS":
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "Bedrock smoke did not pass all profiles",
                "artifact": BEDROCK_ARTIFACT,
            }
        profiles = proof.get("profiles")
        if proof.get("profile_count") != len(PROFILE_KEYS) or not isinstance(profiles, list):
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "v8 Bedrock smoke artifact has incomplete profile evidence",
                "artifact": BEDROCK_ARTIFACT,
            }
        for profile in profiles:
            if not isinstance(profile, dict) or profile.get("status") != "PASS":
                return {
                    "schema_version": "bedrock-model-proof/v2",
                    "status": "NOT_RUN",
                    "reason": "v8 Bedrock smoke artifact contains a non-pass profile",
                    "artifact": BEDROCK_ARTIFACT,
                }
            run = profile.get("agent_run")
            if not isinstance(run, dict):
                return {
                    "schema_version": "bedrock-model-proof/v2",
                    "status": "NOT_RUN",
                    "reason": "v8 Bedrock smoke artifact is missing agent evidence",
                    "artifact": BEDROCK_ARTIFACT,
                }
            closure = run.get("evaluator_citation_closure")
            if (
                not isinstance(closure, dict)
                or closure.get("schema_version") != "evaluator-citation-closure/v1"
                or closure.get("all_synthesis_claims_validated") is not True
                or closure.get("all_admitted_evidence_covered") is not True
            ):
                return {
                    "schema_version": "bedrock-model-proof/v2",
                    "status": "NOT_RUN",
                    "reason": "v9 Bedrock smoke artifact lacks complete citation closure",
                    "artifact": BEDROCK_ARTIFACT,
                }
            coverage = run.get("evaluator_source_coverage")
            if (
                not isinstance(coverage, dict)
                or coverage.get("schema_version") != "evaluator-source-coverage/v2"
                or coverage.get("all_required_sources_validated") is not True
                or coverage.get("all_required_sources_available") is not True
            ):
                return {
                    "schema_version": "bedrock-model-proof/v2",
                    "status": "NOT_RUN",
                    "reason": "v8 Bedrock smoke artifact lacks complete source coverage",
                    "artifact": BEDROCK_ARTIFACT,
                }
        claim_path = self.repository_root / BEDROCK_CLAIM
        try:
            attempt_claim = load_v9_attempt_claim(claim_path)
        except ProviderAttemptClaimError:
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "v8 provider attempt claim is absent or invalid",
                "artifact": BEDROCK_ARTIFACT,
            }
        expected_claim = attempt_claim.model_dump(mode="json")
        if (
            proof.get("attempt_claim") != expected_claim
            or proof.get("attempt_claim_id") != attempt_claim.claim_id
            or proof.get("attempt_claim_digest") != claim_digest(attempt_claim)
        ):
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "v8 provider attempt claim does not match the PASS artifact",
                "artifact": BEDROCK_ARTIFACT,
            }
        if proof.get("version_digests") != self._version_digests():
            return {
                "schema_version": "bedrock-model-proof/v2",
                "status": "NOT_RUN",
                "reason": "Bedrock smoke artifact version digests do not match the current source",
                "artifact": BEDROCK_ARTIFACT,
            }
        # Embed only the public, already-frozen result.  The artifact is not rerun or
        # modified by this offline composer.
        return {
            "schema_version": "bedrock-model-proof/v2",
            "status": "PASS",
            "artifact": BEDROCK_ARTIFACT,
            "proof": proof,
        }

    def run_all(self) -> dict[str, Any]:
        safety = self.business.run_all()
        scripted = self.run_scripted()
        bedrock = self._bedrock_proof()
        authority_b_real = self._authority_b_proof()
        versions = self._version_digests()
        safety_pass = safety.get("status") == "PASS"
        scripted_pass = scripted.get("status") == "PASS"
        real_degradation_evidence = bool(
            authority_b_real.get("evidence_valid") is True
            and authority_b_real.get("outcome_status") == "DEGRADED"
            and authority_b_real.get("usefulness_status") == ProofStatus.FAIL.value
            and authority_b_real.get("stable_real_usefulness_status")
            == EvidenceClass.NOT_PROVEN.value
        )
        promotion_status = (
            M4PromotionStatus.PASS_WITH_DISCLOSED_AI_DEGRADATION
            if safety_pass and scripted_pass and real_degradation_evidence
            else M4PromotionStatus.NOT_READY
        )
        # Authority B keeps the two claims independently inspectable.  The existing
        # safety regression is authoritative; the scripted Strands trace is only an
        # offline usefulness witness and can never promote an operational action.
        safety_proof = {
            "schema_version": "safety-proof/v1",
            "status": "PASS" if safety_pass else "FAIL",
            "evidence_class": EvidenceClass.PROVEN.value,
            "model_independent": True,
            "authority_label": "DETERMINISTIC SAFETY PROOF",
            "source": "authority_b_safety_regression",
            "case_count": safety.get("case_count", 0),
            "safety_counters": safety.get("safety_counters", {}),
        }
        usefulness_proof = {
            "schema_version": "ai-usefulness-proof/v1",
            # This field describes stable real-provider usefulness.  It is never
            # promoted to PASS by a degraded attempt, even when the surrounding
            # M4 acceptance is promoted with disclosure.
            "status": authority_b_real.get(
                "stable_real_usefulness_status", EvidenceClass.NOT_PROVEN.value
            ),
            "evidence_class": EvidenceClass.NOT_PROVEN.value,
            "operational_authority": False,
            "authority_label": "NON-AUTHORITATIVE AI USEFULNESS PROOF",
            "provider": authority_b_real.get("outcome", {}).get("provider", "bedrock")
            if isinstance(authority_b_real.get("outcome"), dict)
            else "bedrock",
            "real_provider": True,
            "artifact": authority_b_real.get("claim"),
            "outcome_status": authority_b_real.get("outcome_status", "NOT_RUN"),
            "advisory_label": "ADVISORY — NOT AN OPERATIONAL DECISION",
        }
        evidence_taxonomy = {
            "deterministic_safety": {
                "class": EvidenceClass.PROVEN.value,
                "status": safety_proof["status"],
            },
            "scripted_synthetic_advisory": {
                "class": EvidenceClass.SCRIPTED_PROOF.value,
                "status": scripted.get("status", "FAIL"),
            },
            "real_nova_integration_and_degradation": {
                "class": (
                    EvidenceClass.PROVEN.value
                    if real_degradation_evidence
                    else EvidenceClass.NOT_PROVEN.value
                ),
                "status": authority_b_real.get("outcome_status", "NOT_RUN"),
            },
            "stable_real_nova_usefulness": {
                "class": EvidenceClass.NOT_PROVEN.value,
                "status": EvidenceClass.NOT_PROVEN.value,
            },
        }
        # Keep the old names in the report for historical consumers, but promotion
        # is now bound to deterministic safety, scripted advisory value, and a
        # validated redacted Authority-B degradation record.  The v9 Bedrock smoke
        # and any stable-usefulness claim cannot satisfy the disclosed acceptance.
        result = {
            "schema_version": "golden-suite/v2",
            "runner_version": RUNNER_VERSION,
            "status": promotion_status.value,
            "evidence_taxonomy": evidence_taxonomy,
            "safety_regression": safety,
            "scripted_strands_proof": scripted,
            "bedrock_model_proof": bedrock,
            "authority_b_safety_proof": safety_proof,
            "authority_b_ai_usefulness_proof": authority_b_real,
            "authority_b_real_proof": authority_b_real,
            "safety_proof": safety_proof,
            "ai_usefulness_proof": usefulness_proof,
            "version_matrix": {
                **versions,
            },
            "promotion": {
                "promotable": promotion_status
                is M4PromotionStatus.PASS_WITH_DISCLOSED_AI_DEGRADATION,
                "status": promotion_status.value,
                "acceptance": {
                    "deterministic_safety_pass": safety_pass,
                    "scripted_synthetic_advisory_pass": scripted_pass,
                    "consumed_real_claim_and_degraded_outcome": real_degradation_evidence,
                    "stable_real_nova_usefulness": EvidenceClass.NOT_PROVEN.value,
                    "plain_pass_implies_real_usefulness": False,
                },
                "reason": (
                    "deterministic safety and scripted advisory proof passed; the consumed "
                    "real Nova attempt is preserved as degraded evidence and stable real "
                    "Nova usefulness remains NOT_PROVEN"
                )
                if promotion_status is M4PromotionStatus.PASS_WITH_DISCLOSED_AI_DEGRADATION
                else "required disclosed-degradation evidence or offline proof is missing",
            },
        }
        _atomic_json(self.artifact_root / "golden-v2.json", result)
        return result
